await act(async () => mock.timers.tick(5001));
assert.ok(document.querySelector('.login-screen'));
assert.match(document.querySelector('.login-message').textContent, /expired/);
assert.equal(window.location.hash, '#/login');
await act(async () => root.unmount());
mock.timers.reset();
dom.window.close();

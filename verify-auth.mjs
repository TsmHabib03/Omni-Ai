import assert from 'node:assert/strict';
import { mock } from 'node:test';
import { mkdirSync } from 'node:fs';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<!doctype html><html><head><link rel="icon"></head><body><div id="root"></div></body></html>', { url: 'https://omni.test/', pretendToBeVisual: true });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, Event: dom.window.Event, MouseEvent: dom.window.MouseEvent, getComputedStyle: dom.window.getComputedStyle.bind(dom.window), requestAnimationFrame: dom.window.requestAnimationFrame.bind(dom.window), IS_REACT_ACT_ENVIRONMENT: true });
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
globalThis.CustomEvent = dom.window.CustomEvent;
dom.window.HTMLElement.prototype.scrollTo = function () {};
mkdirSync('test-results', { recursive: true });
await build({ entryPoints: ['App.jsx'], outfile: 'test-results/AuthApp.test.mjs', bundle: true, format: 'esm', platform: 'node', packages: 'external', loader: { '.css': 'empty' }, define: {
  'import.meta.env': JSON.stringify({ VITE_GOOGLE_CLIENT_ID: 'test-client.apps.googleusercontent.com', VITE_API_BASE_URL: 'https://gateway.test', VITE_TERMS_URL: 'https://omni.test/terms', VITE_PRIVACY_URL: 'javascript:alert(1)' }),
} });
const { default: React, act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { default: App } = await import('./test-results/AuthApp.test.mjs');
const root = createRoot(document.getElementById('root'));
let googleCallback;
window.google = { accounts: { id: { initialize: options => googleCallback = options.callback, renderButton: host => {
  const button = document.createElement('button'); button.textContent = 'Google test sign-in'; host.append(button);
}, disableAutoSelect: () => {} } } };
const button = label => [...document.querySelectorAll('button')].find(b => b.getAttribute('aria-label') === label || b.textContent.trim() === label);
const click = element => act(async () => { assert.ok(element); element.dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true })); });
const input = value => act(async () => {
  const field = document.querySelector('textarea');
  Object.getOwnPropertyDescriptor(dom.window.HTMLTextAreaElement.prototype, 'value').set.call(field, value);
  field.dispatchEvent(new dom.window.Event('input', { bubbles: true }));
});
const submit = () => act(async () => document.querySelector('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true })));
const credential = `header.${Buffer.from(JSON.stringify({ sub: 'alice', email: 'alice@example.test', email_verified: true, name: 'Alice Example', picture: 'https://lh3.googleusercontent.com/test-photo', exp: Math.floor(Date.now() / 1000) + 3600 })).toString('base64url')}.signature`;
const requests = [];
let reply = () => Response.json({ reply: 'Authenticated reply', usage: { remaining: 4, resetAt: Date.now() + 60000 } });
globalThis.fetch = async (url, options) => { if (url.endsWith('/api/config')) return Response.json({ showCarbonWarning: false }); requests.push({ url, ...options, body: JSON.parse(options.body) }); return reply(); };
await act(async () => root.render(React.createElement(App)));
assert.ok(document.querySelector('.login-screen'));
assert.equal(document.querySelector('.app-shell'), null);
assert.equal(document.querySelector('textarea'), null);
assert.equal(window.location.hash, '#/login');
assert.equal(document.querySelector('.login-footer a').href, 'https://omni.test/terms');
assert.equal(document.querySelectorAll('.login-footer a').length, 1, 'Unsafe legal URLs cannot become links');
await act(async () => googleCallback({ credential: 'invalid' }));
assert.match(document.querySelector('.login-message').textContent, /invalid or expired/);
assert.equal(requests.length, 0, 'Signed-out generation must never call a backend');
await act(async () => googleCallback({ credential }));
assert.equal(window.location.hash, '#/app');
assert.equal(document.querySelector('.login-screen'), null);
const avatar = document.querySelector('.bottom-nav .profile-avatar img');
assert.equal(avatar.src, 'https://lh3.googleusercontent.com/test-photo');
assert.equal(avatar.getAttribute('referrerpolicy'), 'no-referrer');
await act(async () => avatar.dispatchEvent(new dom.window.Event('error')));
assert.ok(document.querySelector('.bottom-nav .profile-avatar svg'));
await input('Keep this draft'); await submit();
assert.equal(requests[0].url, 'https://gateway.test/api/chat');
assert.equal(requests[0].headers.Authorization, `Bearer ${credential}`);
assert.equal(requests[0].body.email, 'alice@example.test');
assert.ok(document.querySelector('[role=log]').textContent.includes('Authenticated reply'));
assert.ok(!JSON.stringify({ ...window.localStorage }).includes(credential));
reply = () => Response.json({ error: 'Allowance exhausted', code: 'ACCOUNT_RATE_LIMIT', remaining: 0, retryAfter: 60, resetAt: Date.now() + 60000 }, { status: 429, headers: { 'Retry-After': '60' } });
await input('Second attempt'); await submit();
assert.equal(requests.length, 2);
assert.equal(document.querySelector('textarea').value, 'Second attempt');
assert.ok(button('Wait 60s')?.disabled);
await submit(); assert.equal(requests.length, 2, 'Countdown must prevent another generation');
await click(button('Manage account')); await click(button('Sign out'));
assert.equal(document.querySelectorAll('.user-message').length, 0, 'Sign-out clears account conversation');
assert.ok(document.querySelector('.login-screen'));
assert.equal(document.querySelector('textarea'), null);
assert.equal(window.location.hash, '#/login');
await act(async () => { window.location.hash = '#/app'; await new Promise(resolve => setTimeout(resolve, 20)); });
assert.equal(window.location.hash, '#/login', 'A manual route cannot bypass the sign-in gate');
await act(async () => googleCallback({ credential }));
reply = () => Response.json({ error: 'Expired token' }, { status: 401 });
await input('Try after expiry'); await submit();
assert.ok(document.querySelector('.login-screen'));
assert.equal(document.querySelector('textarea'), null);
assert.match(document.querySelector('.login-message').textContent, /could not be verified/);
await act(async () => googleCallback({ credential }));
assert.equal(document.querySelector('textarea').value, 'Try after expiry');
await click(button('Manage account')); await click(button('Sign out'));
mock.timers.enable({ apis: ['Date', 'setTimeout'], now: Date.now() });
const shortCredential = 'header.' + Buffer.from(JSON.stringify({ email: 'alice@example.test', email_verified: true, picture: 'javascript:alert(1)', exp: (Date.now() + 5000) / 1000 })).toString('base64url') + '.signature';
await act(async () => googleCallback({ credential: shortCredential }));
